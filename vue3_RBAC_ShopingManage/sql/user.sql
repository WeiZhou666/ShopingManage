-- ============================================================
-- 用户模块建表脚本
-- 数据库: MySQL 8.0+
-- 字符集: utf8mb4 / utf8mb4_unicode_ci
-- 包含表: users, user_addresses, operation_logs
--
-- 标签设计说明:
--   优质客户 / 普通客户 / 恶意用户 → 互斥,单选 → tags 字段
--   后端组装前端 tags 数组逻辑:
--     tags=1 → ['优质客户']
--     tags=2 → ['普通客户']
--     tags=3 → ['恶意用户']
-- ============================================================

-- ------------------------------------------------------------
-- 1. users  用户主表
-- ------------------------------------------------------------
CREATE TABLE `users` (
  `id`                BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT       COMMENT '用户ID',
  `nickname`          VARCHAR(20)      NOT NULL                       COMMENT '用户昵称',
  `phone`             VARCHAR(11)      NOT NULL                       COMMENT '手机号',
  `password`          VARCHAR(255)     NOT NULL                       COMMENT '登录密码(bcrypt加密)',
  `register_time`     DATETIME         NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '注册时间',
  `last_login_time`   DATETIME         NULL DEFAULT NULL             COMMENT '最后登录时间',
  `status`            TINYINT          NOT NULL DEFAULT 1             COMMENT '账号状态: 1=正常 0=禁用',
  `tags`              TINYINT          NOT NULL DEFAULT 2             COMMENT '用户标签(互斥): 1=优质客户 2=普通客户 3=恶意用户',
  `total_consumption` DECIMAL(12,2)    NOT NULL DEFAULT 0.00          COMMENT '累计消费金额(冗余,订单完成时更新)',
  `order_count`       INT              NOT NULL DEFAULT 0             COMMENT '订单数(冗余,订单完成时更新)',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_phone` (`phone`),
  KEY `idx_status` (`status`),
  KEY `idx_tags` (`tags`),
  KEY `idx_register_time` (`register_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户主表';


-- ------------------------------------------------------------
-- 2. user_addresses  用户收货地址表
-- ------------------------------------------------------------
CREATE TABLE `user_addresses` (
  `id`         INT             NOT NULL AUTO_INCREMENT      COMMENT '地址ID',
  `user_id`    BIGINT UNSIGNED NOT NULL                      COMMENT '用户ID',
  `name`       VARCHAR(20)     NOT NULL                      COMMENT '收货人姓名',
  `phone`      VARCHAR(11)     NOT NULL                      COMMENT '收货人手机号',
  `address`    VARCHAR(200)    NOT NULL                      COMMENT '详细收货地址',
  `is_default` TINYINT         NOT NULL DEFAULT 0            COMMENT '是否默认: 1=默认 0=非默认',
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`),
  CONSTRAINT `fk_user_addresses_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户收货地址表';


-- ------------------------------------------------------------
-- 3. operation_logs  用户操作日志表
-- ------------------------------------------------------------
CREATE TABLE `operation_logs` (
  `id`         BIGINT          NOT NULL AUTO_INCREMENT      COMMENT '日志ID',
  `user_id`    BIGINT UNSIGNED NOT NULL                      COMMENT '被操作用户ID',
  `operator`   VARCHAR(50)     NOT NULL                      COMMENT '操作人(系统/客服姓名)',
  `action`     VARCHAR(200)    NOT NULL                      COMMENT '操作动作描述',
  `created_at` DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '操作时间',
  PRIMARY KEY (`id`),
  KEY `idx_user_id_created_at` (`user_id`, `created_at` DESC),
  CONSTRAINT `fk_operation_logs_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户操作日志表';


